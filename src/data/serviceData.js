// ==========================================
// CREATE SERVICE SLUG
// ==========================================

export function createServiceSlug(title) {
  return title
    .toLowerCase()
    .trim()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

// ==========================================
// GET SERVICE DETAILS
// ==========================================

export function getServiceDetails(slug, category = "Pet Care") {
  const service = serviceData[slug];

  if (service) {
    return service;
  }

  const title = slug
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");

  return {
    title,
    category,
    image: "",
    shortDescription: `Professional ${title.toLowerCase()} care for your beloved pet.`,
    description: `Our ${title.toLowerCase()} service is designed around your pet's comfort, safety and individual needs. Our team will understand your requirements and provide suitable care throughout the service.`,
    process: [
      {
        title: "Initial consultation",
        description:
          "We understand your pet's needs, preferences and any special instructions.",
      },
      {
        title: "Service preparation",
        description:
          "We prepare the appropriate environment and equipment for the service.",
      },
      {
        title: "Personalised care",
        description:
          "Our team carries out the service with attention to your pet's comfort and wellbeing.",
      },
      {
        title: "Final check",
        description:
          "We check your pet's comfort and make sure the service is completed properly.",
      },
    ],
    benefits: [
      "Care based on your pet's needs",
      "Comfort-focused service",
      "Attentive supervision",
      "A caring environment",
    ],
  };
}
